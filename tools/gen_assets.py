"""Pack web/index.html, a manifest and a home-screen icon into firmware/padkey/web_assets.h"""
import gzip, io, json, os, sys
from PIL import Image, ImageDraw, ImageFilter

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "firmware", "padkey", "web_assets.h")

def icon(size=180):
    img = Image.new("RGB", (size, size), (5, 1, 15))
    d = ImageDraw.Draw(img)
    for y in range(size):  # purple -> teal diagonal glow
        t = y / size
        d.line([(0, y), (size, y)], fill=(int(40 * (1 - t)), int(10 + 30 * t), int(70 - 20 * t)))
    glow = Image.new("RGB", (size, size), (0, 0, 0))
    g = ImageDraw.Draw(glow)
    s = size / 180
    def keyboard(dr, w):
        dr.rounded_rectangle([28 * s, 52 * s, 152 * s, 128 * s], radius=14 * s, outline=(0, 240, 255), width=w)
        for row, y in enumerate((66, 84, 102)):
            n = 7 - (row == 2) * 2
            x0 = 40 + (row == 2) * 22
            for i in range(n):
                dr.rounded_rectangle([(x0 + i * 15) * s, y * s, (x0 + i * 15 + 10) * s, (y + 10) * s], radius=2 * s, fill=(255, 43, 214) if row == 2 and i == 2 else (0, 240, 255))
        dr.rounded_rectangle([58 * s, 116 * s, 122 * s, 121 * s], radius=2 * s, fill=(255, 230, 0))
    keyboard(g, int(8 * s))
    img = Image.blend(img, Image.composite(glow.filter(ImageFilter.GaussianBlur(7 * s)), img, Image.new("L", (size, size), 255)), 0.9)
    keyboard(ImageDraw.Draw(img), int(4 * s))
    buf = io.BytesIO(); img.save(buf, "PNG", optimize=True)
    return buf.getvalue()

def arr(name, data):
    body = ",".join(str(b) for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};\nstatic const size_t {name}_len = {len(data)};\n"

html = open(os.path.join(root, "web", "index.html"), "rb").read()
manifest = json.dumps({
    "name": "PadKey", "short_name": "PadKey", "start_url": "./", "display": "standalone",
    "orientation": "any", "background_color": "#05010f", "theme_color": "#05010f",
    "icons": [{"src": "icon.png", "sizes": "180x180", "type": "image/png"}],
}).encode()
png = icon()
open(os.path.join(root, "web", "icon-preview.png"), "wb").write(png)
with open(out, "w") as f:
    f.write("// Generated by tools/gen_assets.py — do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    f.write(arr("index_html_gz", gzip.compress(html, 9, mtime=0)))
    f.write(arr("manifest_json_gz", gzip.compress(manifest, 9, mtime=0)))
    f.write(arr("icon_png", png))
print("assets:", len(html), "->", len(gzip.compress(html, 9)), "bytes html; icon", len(png))

# Static copy for GitHub Pages (Bluetooth mode needs https).
site = os.path.join(root, "docs")
os.makedirs(site, exist_ok=True)
open(os.path.join(site, "index.html"), "wb").write(html)
open(os.path.join(site, "manifest.json"), "wb").write(manifest)
open(os.path.join(site, "icon.png"), "wb").write(png)
open(os.path.join(site, "apple-touch-icon.png"), "wb").write(png)
open(os.path.join(site, ".nojekyll"), "w").close()
import shutil
for extra in ("zhuyin.txt", "zhuyin-LICENSE.txt"):
    shutil.copy(os.path.join(root, "web", extra), os.path.join(site, extra))
